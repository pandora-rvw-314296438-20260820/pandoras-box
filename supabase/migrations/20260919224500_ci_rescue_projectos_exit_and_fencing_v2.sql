create or replace function private.pandora_ci_rescue_guard_v2()
returns trigger
language plpgsql
security definer
set search_path to 'pg_catalog', 'private', 'public'
as $function$
declare
  v_allowed boolean := false;
begin
  if new.repository is distinct from old.repository
     or new.branch is distinct from old.branch
     or new.origin_failing_sha is distinct from old.origin_failing_sha
     or new.delivery_id is distinct from old.delivery_id
     or new.idempotency_key is distinct from old.idempotency_key
     or new.pr_number is distinct from old.pr_number
     or new.external_event_id is distinct from old.external_event_id then
    raise exception 'ci rescue immutable provenance changed' using errcode='55000';
  end if;

  if old.status in ('completed','superseded','blocked','failed') then
    raise exception 'ci rescue terminal state is immutable' using errcode='55000';
  end if;

  if new.source_attempt_count < old.source_attempt_count
     or new.source_attempt_count > old.source_attempt_count + 1
     or new.source_attempt_count > 2 then
    raise exception 'ci rescue source attempt violation' using errcode='55000';
  end if;

  if new.transient_retry_count < old.transient_retry_count
     or new.transient_retry_count > old.transient_retry_count + 1
     or new.transient_retry_count > 1
     or (old.transient_retry_consumed and not new.transient_retry_consumed)
     or new.transient_retry_consumed is distinct from (new.transient_retry_count = 1) then
    raise exception 'ci rescue transient retry violation' using errcode='55000';
  end if;

  if new.claim_generation < old.claim_generation
     or new.claim_generation > old.claim_generation + 1 then
    raise exception 'ci rescue claim generation violation' using errcode='55000';
  end if;

  if new.claim_generation = old.claim_generation + 1 then
    if nullif(new.claimed_by,'') is null
       or new.lease_token is null
       or new.lease_until is null
       or new.lease_until <= clock_timestamp() then
      raise exception 'ci rescue invalid fenced claim' using errcode='55000';
    end if;
  elsif new.claimed_by is distinct from old.claimed_by and new.claimed_by is not null then
    raise exception 'ci rescue claimant changed without generation bump' using errcode='55000';
  end if;

  if new.lease_token is distinct from old.lease_token
     and new.lease_token is not null
     and new.claim_generation <> old.claim_generation + 1 then
    raise exception 'ci rescue lease token changed without generation bump' using errcode='55000';
  end if;

  if new.status = old.status then
    v_allowed := true;
  elsif old.status='queued' and new.status in ('retrying','analyzing','blocked','superseded','failed') then
    v_allowed := true;
  elsif old.status='retrying' and new.status in ('analyzing','verifying','blocked','superseded','failed') then
    v_allowed := true;
  elsif old.status='analyzing' and new.status in ('repairing','blocked','superseded','failed') then
    v_allowed := true;
  elsif old.status='repairing' and new.status in ('verifying','blocked','superseded','failed') then
    v_allowed := true;
  elsif old.status='verifying' and new.status in ('completed','analyzing','blocked','superseded','failed') then
    v_allowed := true;
  end if;

  if not v_allowed then
    raise exception 'ci rescue illegal state transition % -> %', old.status, new.status using errcode='55000';
  end if;

  if new.source_attempt_count = old.source_attempt_count + 1 and new.status <> 'repairing' then
    raise exception 'source attempt may increment only when entering repairing' using errcode='55000';
  end if;

  if new.transient_retry_count = old.transient_retry_count + 1 and new.status <> 'retrying' then
    raise exception 'transient retry may increment only when entering retrying' using errcode='55000';
  end if;

  if new.status='superseded'
     and new.superseded_by_sha is null
     and coalesce(new.last_error_code,'') <> 'LEGACY_PROJECTOS_QUEUE_QUARANTINED' then
    raise exception 'superseded rescue requires successor sha' using errcode='55000';
  end if;

  if new.status in ('completed','superseded','blocked','failed') then
    if new.completed_at is null then
      raise exception 'terminal rescue requires completed_at' using errcode='55000';
    end if;
  elsif new.completed_at is not null then
    raise exception 'nonterminal rescue cannot have completed_at' using errcode='55000';
  end if;

  return new;
end;
$function$;

