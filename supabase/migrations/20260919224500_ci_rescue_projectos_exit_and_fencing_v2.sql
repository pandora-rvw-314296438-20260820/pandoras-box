create or replace function private.pandora_ci_rescue_agent_config_v2()
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_url text;
  v_secret text;
begin
  select decrypted_secret into v_url
  from vault.decrypted_secrets
  where name='pandora_ci_rescue_agent_url'
  order by created_at desc
  limit 1;

  select decrypted_secret into v_secret
  from vault.decrypted_secrets
  where name='pandora_ci_rescue_agent_secret'
  order by created_at desc
  limit 1;

  if v_url !~ '^https://'
     or nullif(v_secret,'') is null
     or length(v_secret) < 32 then
    return jsonb_build_object('configured',false);
  end if;

  return jsonb_build_object('configured',true,'url',v_url,'secret',v_secret);
end;
$function$;

