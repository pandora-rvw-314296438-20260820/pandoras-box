create or replace function private.pandora_ci_rescue_audit_trigger_v2()
returns trigger
language plpgsql
security definer
set search_path to 'pg_catalog', 'private', 'public'
as $function$
declare
  v_actor text;
  v_event text;
begin
  v_actor := nullif(current_setting('app.actor', true),'');
  if v_actor is null then
    v_actor := session_user;
  end if;

  if tg_op='INSERT' then
    v_event := 'enqueued';
    insert into private.pandora_ci_rescue_audit_events(
      rescue_id, actor, event_type, claim_generation, previous_state, new_state, evidence_reference
    ) values (
      new.id, v_actor, v_event, new.claim_generation, null, to_jsonb(new),
      coalesce(new.evidence->'evidenceReference','{}'::jsonb)
    );
    return new;
  end if;

  if new.claim_generation = old.claim_generation + 1 then
    v_event := 'claimed';
  elsif new.status is distinct from old.status then
    v_event := 'transition';
  else
    v_event := 'updated';
  end if;

  insert into private.pandora_ci_rescue_audit_events(
    rescue_id, actor, event_type, claim_generation, previous_state, new_state, evidence_reference
  ) values (
    new.id, v_actor, v_event, new.claim_generation, to_jsonb(old), to_jsonb(new),
    coalesce(new.evidence->'evidenceReference','{}'::jsonb)
  );
  return new;
end;
$function$;

