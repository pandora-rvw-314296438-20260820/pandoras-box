create or replace function public.pandora_ci_rescue_enqueue_v2(
  p_delivery_id uuid,
  p_repository text,
  p_branch text,
  p_head_sha text,
  p_workflow_run_id bigint,
  p_workflow_name text,
  p_pr_number integer default null,
  p_evidence jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog', 'private', 'public'
as $function$
declare
  v_org uuid;
  v_name text := left(trim(coalesce(p_workflow_name,'')),200);
  v_sha text := lower(trim(coalesce(p_head_sha,'')));
  v_branch text := trim(coalesce(p_branch,''));
  v_key text;
  v_row private.pandora_ci_rescue_jobs%rowtype;
begin
  perform private.assert_control_service_role();
  perform set_config('app.actor','webhook:pandora-github-webhook',true);

  if p_repository <> 'pandora-rvw-314296438-20260820/pandoras-box'
     or v_branch='' or v_branch='main'
     or v_branch !~ '^[A-Za-z0-9._/-]{1,220}$'
     or v_sha !~ '^[0-9a-f]{40}$'
     or p_workflow_run_id is null or p_workflow_run_id < 1
     or p_delivery_id is null
     or (p_pr_number is not null and p_pr_number < 1) then
    raise exception 'invalid ci rescue enqueue payload' using errcode='22023';
  end if;

  if not exists (
    select 1 from private.pandora_ci_rescue_workflow_allowlist
    where workflow_name=v_name and enabled
  ) then
    return jsonb_build_object('accepted',false,'reason','workflow_not_eligible','workflow',v_name);
  end if;

  select organization_id into v_org
  from private.project_canonical_registry
  where canonical_provider='github'
    and canonical_repository=p_repository
    and canonical_ref='refs/heads/main'
  order by updated_at desc
  limit 1;

  if v_org is null then
    raise exception 'canonical project registry missing' using errcode='55000';
  end if;

  v_key := p_repository || ':' || coalesce(p_pr_number,0)::text || ':' || v_sha || ':' || p_workflow_run_id::text;

  insert into private.pandora_ci_rescue_jobs(
    external_event_id, delivery_id, organization_id, repository, branch,
    origin_failing_sha, current_failing_sha, workflow_run_id, workflow_name,
    pr_number, idempotency_key, evidence
  ) values (
    null, p_delivery_id, v_org, p_repository, v_branch,
    v_sha, v_sha, p_workflow_run_id, v_name,
    p_pr_number, v_key,
    coalesce(p_evidence,'{}'::jsonb) || jsonb_build_object(
      'deliveryId',p_delivery_id,
      'enqueuedAt',clock_timestamp()
    )
  )
  on conflict (idempotency_key) do nothing;

  select * into v_row
  from private.pandora_ci_rescue_jobs
  where idempotency_key=v_key;

  return jsonb_build_object(
    'accepted',true,
    'id',v_row.id,
    'status',v_row.status,
    'idempotencyKey',v_row.idempotency_key,
    'claimGeneration',v_row.claim_generation
  );
end;
$function$;

create or replace function public.pandora_ci_rescue_claim_v2(
  p_claimed_by text,
  p_limit integer default 2
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog', 'private', 'public'
as $function$
declare
  v_result jsonb;
  v_actor text := trim(coalesce(p_claimed_by,''));
begin
  perform private.assert_control_service_role();
  if v_actor !~ '^[A-Za-z0-9._:/-]{3,120}$' then
    raise exception 'invalid ci rescue claimant' using errcode='22023';
  end if;
  if p_limit < 1 or p_limit > 4 then
    raise exception 'invalid ci rescue claim limit' using errcode='22023';
  end if;
  perform set_config('app.actor',v_actor,true);

  with picked as (
    select j.id
    from private.pandora_ci_rescue_jobs j
    where j.status in ('queued','retrying','verifying')
      and j.delivery_id is not null
      and (j.lease_until is null or j.lease_until < clock_timestamp())
    order by j.created_at
    for update skip locked
    limit p_limit
  ), leased as (
    update private.pandora_ci_rescue_jobs j
       set claimed_by=v_actor,
           claim_generation=j.claim_generation+1,
           lease_token=gen_random_uuid(),
           lease_until=clock_timestamp()+interval '3 minutes',
           updated_at=clock_timestamp()
      from picked p
     where j.id=p.id
     returning j.*
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',id,
    'deliveryId',delivery_id,
    'organizationId',organization_id,
    'repository',repository,
    'branch',branch,
    'originFailingSha',origin_failing_sha,
    'currentFailingSha',current_failing_sha,
    'workflowRunId',workflow_run_id,
    'workflowName',workflow_name,
    'prNumber',pr_number,
    'status',status,
    'sourceAttemptCount',source_attempt_count,
    'transientRetryCount',transient_retry_count,
    'transientRetryConsumed',transient_retry_consumed,
    'claimGeneration',claim_generation,
    'claimedBy',claimed_by,
    'leaseToken',lease_token,
    'evidence',evidence
  ) order by created_at),'[]'::jsonb)
  into v_result from leased;

  return v_result;
end;
$function$;

create or replace function public.pandora_ci_rescue_transition_v2(
  p_id uuid,
  p_claimed_by text,
  p_claim_generation bigint,
  p_lease_token uuid,
  p_status text,
  p_patch jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog', 'private', 'public'
as $function$
declare
  v_row private.pandora_ci_rescue_jobs%rowtype;
  v_patch jsonb := coalesce(p_patch,'{}'::jsonb);
  v_source_attempts integer;
  v_transient_attempts integer;
  v_current_sha text;
  v_run_id bigint;
  v_repair_sha text;
  v_superseded_sha text;
  v_provider text;
  v_error text;
  v_evidence jsonb;
begin
  perform private.assert_control_service_role();
  if p_status not in ('queued','retrying','analyzing','repairing','verifying','completed','superseded','blocked','failed') then
    raise exception 'invalid ci rescue status' using errcode='22023';
  end if;
  if (v_patch - array[
    'sourceAttemptCount','transientRetryCount','currentFailingSha','workflowRunId',
    'repairCommitSha','supersededBySha','modelProvider','lastErrorCode','evidence','evidenceReference'
  ]) <> '{}'::jsonb then
    raise exception 'invalid ci rescue patch keys' using errcode='22023';
  end if;

  select * into v_row
  from private.pandora_ci_rescue_jobs
  where id=p_id
    and claimed_by=p_claimed_by
    and claim_generation=p_claim_generation
    and lease_token=p_lease_token
    and lease_until is not null
    and lease_until >= clock_timestamp()
  for update;

  if v_row.id is null then
    raise exception 'ci rescue stale claim' using errcode='55000';
  end if;

  perform set_config('app.actor',p_claimed_by,true);

  v_source_attempts := coalesce((v_patch->>'sourceAttemptCount')::integer,v_row.source_attempt_count);
  v_transient_attempts := coalesce((v_patch->>'transientRetryCount')::integer,v_row.transient_retry_count);
  v_current_sha := lower(coalesce(nullif(v_patch->>'currentFailingSha',''),v_row.current_failing_sha));
  v_run_id := coalesce((v_patch->>'workflowRunId')::bigint,v_row.workflow_run_id);
  v_repair_sha := case when v_patch ? 'repairCommitSha' then nullif(lower(v_patch->>'repairCommitSha'),'') else v_row.repair_commit_sha end;
  v_superseded_sha := case when v_patch ? 'supersededBySha' then nullif(lower(v_patch->>'supersededBySha'),'') else v_row.superseded_by_sha end;
  v_provider := case when v_patch ? 'modelProvider' then nullif(left(v_patch->>'modelProvider',40),'') else v_row.model_provider end;
  v_error := case when v_patch ? 'lastErrorCode' then nullif(left(v_patch->>'lastErrorCode',160),'') else v_row.last_error_code end;
  v_evidence := v_row.evidence
    || coalesce(v_patch->'evidence','{}'::jsonb)
    || case when v_patch ? 'evidenceReference'
            then jsonb_build_object('evidenceReference',v_patch->'evidenceReference')
            else '{}'::jsonb end;

  if v_source_attempts not between 0 and 2
     or v_transient_attempts not between 0 and 1
     or v_current_sha !~ '^[0-9a-f]{40}$'
     or (v_repair_sha is not null and v_repair_sha !~ '^[0-9a-f]{40}$')
     or (v_superseded_sha is not null and v_superseded_sha !~ '^[0-9a-f]{40}$')
     or v_run_id < 1 then
    raise exception 'invalid ci rescue patch values' using errcode='22023';
  end if;

  update private.pandora_ci_rescue_jobs
     set status=p_status,
         source_attempt_count=v_source_attempts,
         transient_retry_count=v_transient_attempts,
         transient_retry_consumed=(v_transient_attempts=1),
         current_failing_sha=v_current_sha,
         workflow_run_id=v_run_id,
         repair_commit_sha=v_repair_sha,
         superseded_by_sha=v_superseded_sha,
         model_provider=v_provider,
         last_error_code=v_error,
         evidence=v_evidence,
         claimed_by=null,
         lease_token=null,
         lease_until=null,
         updated_at=clock_timestamp(),
         completed_at=case when p_status in ('completed','superseded','blocked','failed') then clock_timestamp() else null end
   where id=p_id
     and claimed_by=p_claimed_by
     and claim_generation=p_claim_generation
     and lease_token=p_lease_token
   returning * into v_row;

  if v_row.id is null then
    raise exception 'ci rescue stale claim' using errcode='55000';
  end if;

  return jsonb_build_object(
    'id',v_row.id,
    'status',v_row.status,
    'sourceAttemptCount',v_row.source_attempt_count,
    'transientRetryCount',v_row.transient_retry_count,
    'currentFailingSha',v_row.current_failing_sha,
    'workflowRunId',v_row.workflow_run_id,
    'repairCommitSha',v_row.repair_commit_sha,
    'supersededBySha',v_row.superseded_by_sha,
    'claimGeneration',v_row.claim_generation,
    'updatedAt',v_row.updated_at,
    'completedAt',v_row.completed_at
  );
end;
$function$;

